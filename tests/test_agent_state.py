"""Unit tests for AgentState schema and add_messages reducer.

Tests:
1. AgentState schema validation and `create_initial_state` defaults/custom values.
2. Independent message list copy verification.
3. `add_messages` reducer semantics (append vs ID-based in-place upsert).
4. Uniform reducer behavior across SystemMessage, HumanMessage, AIMessage, and ToolMessage.
"""

from __future__ import annotations

import pytest
from langchain_core.messages import AIMessage, BaseMessage, HumanMessage, SystemMessage, ToolMessage
from langgraph.graph.message import add_messages

from agent.state import AgentState, create_initial_state


class TestAgentStateInitialization:
    """Test state definition and initial state construction helper."""

    def test_create_initial_state_defaults(self) -> None:
        """Verify default values generated by create_initial_state."""
        state = create_initial_state()

        assert state["messages"] == []
        assert state["step_count"] == 0
        assert state["last_sql"] is None
        assert state["last_error"] is None
        assert state["sql_retry_count"] == 0

    def test_create_initial_state_custom_values(self) -> None:
        """Verify explicit initialization with custom parameters."""
        initial_msg = HumanMessage(content="Calculate total sales")
        state = create_initial_state(
            messages=[initial_msg],
            step_count=5,
            last_sql="SELECT 1;",
            last_error="Syntax error",
            sql_retry_count=2,
        )

        assert len(state["messages"]) == 1
        assert state["messages"][0].content == "Calculate total sales"
        assert state["step_count"] == 5
        assert state["last_sql"] == "SELECT 1;"
        assert state["last_error"] == "Syntax error"
        assert state["sql_retry_count"] == 2

    def test_create_initial_state_copies_messages_list(self) -> None:
        """Ensure initial state creates a shallow copy of messages list rather than sharing mutable reference."""
        msgs = [HumanMessage(content="Query 1")]
        state = create_initial_state(messages=msgs)
        msgs.append(HumanMessage(content="Query 2"))

        assert len(state["messages"]) == 1


class TestAddMessagesReducerDirectly:
    """Directly test the behavior of LangGraph's `add_messages` reducer."""

    def test_add_messages_appends_distinct_messages(self) -> None:
        """Different messages without IDs are appended sequentially."""
        existing = [HumanMessage(content="Hello")]
        new_msgs = [AIMessage(content="Hi there!")]

        result = add_messages(existing, new_msgs)

        assert len(result) == 2
        assert result[0].content == "Hello"
        assert result[1].content == "Hi there!"

    def test_add_messages_upserts_matching_id(self) -> None:
        """Messages sharing an ID are updated in-place rather than appended."""
        m1 = HumanMessage(content="Initial question", id="msg-001")
        m2 = HumanMessage(content="Revised question", id="msg-001")

        result = add_messages([m1], [m2])

        assert len(result) == 1
        assert result[0].content == "Revised question"
        assert result[0].id == "msg-001"

    def test_add_messages_with_system_and_tool_messages(self) -> None:
        """Reducer works uniformly across diverse LangChain BaseMessage subclasses."""
        sys_msg = SystemMessage(content="System prompt", id="sys-1")
        user_msg = HumanMessage(content="User query", id="usr-1")
        ai_msg = AIMessage(content="AI answer", id="ai-1")
        tool_msg = ToolMessage(content="Tool output", tool_call_id="call_123", id="tool-1")

        merged = add_messages([], [sys_msg, user_msg])
        assert len(merged) == 2

        updated = add_messages(merged, [ai_msg, tool_msg])
        assert len(updated) == 4
        assert [m.id for m in updated] == ["sys-1", "usr-1", "ai-1", "tool-1"]
